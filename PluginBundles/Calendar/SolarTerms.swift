    /// 某年第 index 个节气（按公历的顺序）在当月的哪一天；年份不在表里时为 nil
    static func day(ofTerm index: Int, in year: Int) -> Int? {
        guard (firstYear...lastYear).contains(year), names.indices.contains(index) else { return nil }
        let position = (year - firstYear) * names.count + index
        guard offsets.indices.contains(position) else { return nil }
        return earliestDays[index] + Int(offsets[position])
    }

    /// 某年某月第 index 个节气的月份
    static func month(ofTerm index: Int) -> Int {
        index / 2 + 1
    }

    /// 这一天是哪个节气（在 names 里的序号），不是节气时为 nil
    static func term(year: Int, month: Int, day: Int) -> Int? {
